"""Write the README's results section from reports/metrics.json.

CLAUDE.md: result numbers are never typed into the README by hand. Everything
between the two markers below is generated; edit the rest of the README freely.

Run with:  python -m forecast.readme
"""

from __future__ import annotations

import json
import re
from pathlib import Path

import pandas as pd

from forecast import REPO_ROOT
from forecast.backtest import REPORTS_DIR
from forecast.export import FLAG_LABELS

START, END = "<!-- results:start -->", "<!-- results:end -->"
METHODS = {"naive": "Naive (last week)", "snaive": "Seasonal naive (same week last year)",
           "ma4": "4-week moving average", "hgbr": "**HistGradientBoosting, Poisson (main model)**",
           "xgb": "XGBoost, Poisson", "p50": "HistGradientBoosting, P50 (quantile)"}


def compare(model: float, base: float, lower_is_better: bool = True, tol: float = 0.005) -> str:
    """'better than', 'about level with' or 'worse than', from two numbers."""
    if abs(model - base) < tol:
        return "about level with"
    return "better than" if (model < base) == lower_is_better else "worse than"


def results_markdown(metrics: dict, volume_bands: pd.DataFrame) -> str:
    """The generated results section (markdown, without the markers)."""
    overall = {(r["level"], r["method"]): r for r in metrics["models"]["overall"]}
    cov = {r["method"]: r["coverage"] for r in metrics["models"]["p90_coverage"]}
    inv = metrics["inventory"]
    pol = {r["policy"]: r for r in inv["policies"]}
    exc = metrics["exceptions"]
    item, dept = "item-store-week", "dept-store-week"
    top = volume_bands.set_index("band").loc["top 1%"]

    lines = [
        f"*Generated by `python -m forecast.readme` from `reports/metrics.json`. "
        f"Backtest: {len(metrics['origins'])} forecast origins × {len(metrics['horizons'])} "
        f"weeks ahead, {metrics['n_series']:,} item-stores.*",
        "",
        f"- **Stocking:** driving orders with the model's P90 instead of a moving-average "
        f"baseline reaches the same fill rate with **{inv['inventory_saving_at_equal_fill_rate']:.1%} "
        f"less inventory** (simulated: weekly review, 1-week lead time, lost sales).",
        f"- **Accuracy:** department-level WAPE {overall[(dept, 'hgbr')]['wape']:.1%} vs "
        f"{overall[(dept, 'ma4')]['wape']:.1%} for the 4-week moving average. Per item and week "
        f"the model ({overall[(item, 'hgbr')]['wape']:.1%}) is "
        f"{compare(overall[(item, 'hgbr')]['wape'], overall[(item, 'ma4')]['wape'])} the "
        f"moving average ({overall[(item, 'ma4')]['wape']:.1%}).",
        f"- **Uncertainty:** P90 coverage {cov['p90']:.1%} (target 90%) vs "
        f"{cov['baseline_p90']:.1%} for the baseline P90.",
        f"- **Known weakness:** on the top 1% of item-stores by volume ({top['share_of_units']:.0%} "
        f"of units) HGBR's WAPE is {top['wape_hgbr']:.1%} vs {top['wape_ma4']:.1%} for the moving "
        f"average. See `docs/decisions.md`.",
        "",
        "| Method | WAPE item-store-week | WAPE dept-store-week | Bias |",
        "|---|---|---|---|",
    ]
    for key, label in METHODS.items():
        i, d = overall[(item, key)], overall[(dept, key)]
        lines.append(f"| {label} | {i['wape']:.1%} | {d['wape']:.1%} | {i['bias']:+.1%} |")

    lines += [
        "",
        "| Stocking policy (simulated) | Fill rate | Avg units on hand | Stockout weeks |",
        "|---|---|---|---|",
    ]
    for key, label in [("baseline", "Baseline P90 (moving average + past errors)"),
                       ("model", "Model P90")]:
        p = pol[key]
        lines.append(f"| {label} | {p['fill_rate']:.1%} | {p['avg_on_hand']:.2f} | "
                     f"{p['stockout_week_share']:.1%} |")
    lines += [
        "",
        "Inventory saving at equal fill rate, by target: " + ", ".join(
            f"{r['fill_rate']:.0%} → {r['inventory_saving']:.1%}"
            for r in inv["saving_by_target_fill_rate"]) + ".",
        "",
        f"Exception flags in the planning week (starting {exc['as_of_week_start']}): "
        + ", ".join(f"{n} {FLAG_LABELS[k].lower()}" for k, n in exc["flag_counts"].items())
        + f" ({exc['n_flagged_series']} item-stores).",
    ]
    return "\n".join(lines)


def update_readme(readme: str, block: str) -> str:
    """Replace the text between the markers with `block`."""
    pattern = re.compile(re.escape(START) + ".*?" + re.escape(END), re.DOTALL)
    if not pattern.search(readme):
        raise ValueError(f"README has no {START} ... {END} block")
    return pattern.sub(lambda _: f"{START}\n{block}\n{END}", readme)


def main(path: Path = REPO_ROOT / "README.md") -> None:
    metrics = json.loads((REPORTS_DIR / "metrics.json").read_text())
    bands = pd.read_csv(REPORTS_DIR / "volume_bands.csv")
    path.write_text(update_readme(path.read_text(), results_markdown(metrics, bands)))
    print(f"Updated the results section of {path.name}")


if __name__ == "__main__":
    main()
